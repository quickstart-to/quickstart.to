#!/usr/bin/env node
// Generates site/public/_redirects (Cloudflare Workers static assets) from topic.yaml `aliases`.
// Aliases are marketing shortcuts only: 301 to the canonical ASCII slug, never canonical themselves.
import { writeFileSync, mkdirSync } from 'node:fs';
import { join } from 'node:path';
import { ROOT, loadAllTopics } from './lib/topics.mjs';

const lines = ['# Generated by scripts/gen-redirects.mjs — do not edit by hand.'];
for (const { topic } of loadAllTopics()) {
  if (!topic?.slug) continue;
  for (const alias of topic.aliases ?? []) {
    const enc = '/' + encodeURIComponent(alias.normalize('NFC'));
    lines.push(`${enc} /${topic.slug} 301`);
    lines.push(`${enc}/* /${topic.slug}/:splat 301`);
  }
}

const outDir = join(ROOT, 'site', 'public');
mkdirSync(outDir, { recursive: true });
writeFileSync(join(outDir, '_redirects'), lines.join('\n') + '\n');
console.log(`wrote ${lines.length - 1} redirect rule(s) to site/public/_redirects`);
